// SRAM 结构：
//   深度 = 8 个 Word（地址范围 0~7，3-bit 宽度）
//   位宽 = 32 bits（每个 Word 存放 4 字节，对应 APB 一次写入的数据）
//   对应关系：
//      mem[0] = PKT_MEM 地址 0x040 = Byte 0~3   （包头：pkt_len/pkt_type/flags/hdr_chk）
//      mem[1] = PKT_MEM 地址 0x044 = Byte 4~7   （payload 起始）
//         ...
//      mem[7] = PKT_MEM 地址 0x05C = Byte 28~31（payload 最后 4 字节）

// 读时序说明（同步读，1 拍延迟）：
//   - rd_en=1 时，在时钟上升沿将 mem[rd_addr] 锁存到 rd_data
//   - rd_data 在 rd_en 有效的**下一拍**输出稳定值
//   - rd_en=0 时，rd_data 保持上一次的读取值（Hold 行为）
//   → M3 的 FSM 设计需考虑此 1-拍延迟

// 写时序说明（同步写）：
//   - wr_en=1 时，在时钟上升沿将 wr_data 写入 mem[wr_addr]
//   - 复位期间（rst_n=0）：所有存储单元清零（便于仿真调试初始状态观察）

`timescale 1ns/1ps

module packet_sram (
  // ============================================================================
  // 时钟与复位接口
  // ============================================================================
  input  wire       clk,      // 时钟信号 (来自 ppa_top, 映射自 PCLK)
  input  wire       rst_n,    // 异步低有效复位信号 (来自 ppa_top, 映射自 PRESETn)

  // ============================================================================
  // 写端口 (W Port) --- 来自 M1 apb_slave_if
  // ============================================================================
  input  wire       wr_en,      // 写使能: 高有效, 配合时钟上升沿完成写入
  input  wire [2:0] wr_addr,    // 写地址: 3-bit, 范围 0~7, 对应 8 个 Word
  input  wire [31:0] wr_data,   // 写数据: 32-bit, M1 从 APB PWDATA 中透传

  // ============================================================================
  // 读端口0 (R Port 0) --- 来自 M3 packet_proc_core
  // ============================================================================
  input  wire       rd_en,      // 读使能: 高有效, 触发同步读取 (下一拍输出有效数据)
  input  wire [2:0] rd_addr,    // 读地址: 3-bit, 范围 0~7, M3 按包长控制递增
  output reg  [31:0] rd_data,   // 读数据: 同步输出, rd_en 有效后下一拍稳定

  // ============================================================================
  // 读端口1 (R Port 1) --- 来自 M1 apb_slave_if (APB 读取 PKT_MEM) v1.02 新增
  // ============================================================================
  input  wire       rd_en_1,      // 读使能1: 高有效, APB 读 PKT_MEM 时有效
  input  wire [2:0] rd_addr_1,    // 读地址1: 3-bit, 来自 PADDR[4:2]
  output reg  [31:0] rd_data_1    // 读数据1: 同步输出, 送回 M1 的 PRDATA 路径
);


// ============================================================================
// 内部存储阵列定义
// ============================================================================
// 8 个 32-bit 寄存器构成的小型寄存器堆, 行为上等价于片上单端口 SRAM
// 综合工具在映射到实际 FPGA/ASIC 时会识别此 always 结构并推断 Block RAM
reg [31:0] mem [0:7];

// 循环变量 (用于复位时初始化所有存储单元)
integer i;


// ============================================================================
// 写端口逻辑 (同步写, 异步复位)
// ============================================================================
// 时序: wr_en=1 时, clk 上升沿将 wr_data 写入 mem[wr_addr]
// 复位: rst_n=0 时, 将所有存储单元异步清零, 便于仿真观察初始状态
always @(posedge clk or negedge rst_n) begin
  if (!rst_n) begin
    // 异步复位: 清零所有 8 个存储单元
    // 注意: 实际物理 SRAM 复位后内容不确定, 此处仅用于仿真调试
    for (i = 0; i < 8; i = i + 1) begin
      mem[i] <= 32'h0000_0000;
    end
  end else if (wr_en) begin
    // 写使能有效: 在时钟上升沿将写数据存入对应地址
    // wr_addr 为 3-bit, 合法范围 0~7, 硬件不做越界保护
    mem[wr_addr] <= wr_data;
  end
  // wr_en=0 时: 保持原内容不变
end


// ============================================================================
// 读端口0逻辑 (同步读, 带 rd_en 控制, 1 拍延迟) --- 供 M3 使用
// ============================================================================
// 时序: rd_en=1 时, clk 上升沿采样 rd_addr, 下一拍 rd_data 输出有效
// 复位: rst_n=0 时, rd_data 输出清零 (异步清零)

// 【关键说明】同步读 vs 异步读:
//   本模块选择"同步读 (registered output)", 原因:
//   1. 与实际综合可映射到 Block RAM 的行为一致 (更贴近真实 ASIC 行为)
//   2. M3 的 FSM 需实现 pipeline 式取指 (发出地址后, 下一拍处理读出的数据)
//   3. 异步读虽然更简单, 但不可综合为 Block RAM, 不符合工程实践
// ============================================================================

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        rd_data <= 32'h0000_0000;        // 异步复位: 读端口0输出清零
    end else if (rd_en) begin
        rd_data <= mem[rd_addr];         // 锁存 mem[rd_addr], 下一拍有效
    end
    // rd_en=0: 保持上次读取结果 (Hold 模式)
end


// ============================================================================
// 读端口1逻辑 (同步读, 带 rd_en_1 控制, 1 拍延迟) --- 供 M1 APB 读 PKT_MEM 使用
// ============================================================================
// v1.02 新增: 支持 APB Master 通过 M1 读取 SRAM 中已写入的数据包内容
// 时序与读端口0完全相同: rd_en_1=1 时, 下一拍 rd_data_1 输出稳定值
// ============================================================================

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        rd_data_1 <= 32'h0000_0000;      // 异步复位: 读端口1输出清零
    end else if (rd_en_1) begin
        rd_data_1 <= mem[rd_addr_1];     // 锁存 mem[rd_addr_1], 下一拍有效
    end
    // rd_en_1=0: 保持上次读取结果 (Hold 模式)
end

endmodule
// ===========================================================================
